package ua.edu.nupp.kpp.server;

/**
 * Стани життєвого циклу інциденту.
 *
 * <p>Інцидент — об'єкт життєвого циклу з чотирма станами:</p>
 * <pre>
 *   ПОВІДОМЛЕНО → ПІДТВЕРДЖЕНО → РЕАГУВАННЯ → ЗАКРИТО
 *   NEW         → CONFIRMED    → RESPONSE   → CLOSED
 * </pre>
 *
 * <p>Перелік фіксує лише допустимі стани. Правила переходів між ними
 * перевірятимуться на Service-рівні (на наступних етапах).</p>
 */
public enum IncidentState {

    /** ПОВІДОМЛЕНО — інцидент зареєстровано. */
    NEW("ПОВІДОМЛЕНО"),

    /** ПІДТВЕРДЖЕНО — інцидент підтверджено диспетчером. */
    CONFIRMED("ПІДТВЕРДЖЕНО"),

    /** РЕАГУВАННЯ — виїзд бригади, виконуються заходи. */
    RESPONSE("РЕАГУВАННЯ"),

    /** ЗАКРИТО — інцидент ліквідовано. */
    CLOSED("ЗАКРИТО");

    /** Українська назва стану для відображення у клієнтському інтерфейсі. */
    private final String title;

    IncidentState(String title) {
        this.title = title;
    }

    /** @return українська назва стану. */
    public String getTitle() {
        return title;
    }

    /** @return true, якщо це кінцевий стан життєвого циклу. */
    public boolean isFinal() {
        return this == CLOSED;
    }
}
